#!/usr/bin/env bash
# Check: monitor can still read nodes, metrics and stats
set -uo pipefail
  fail=0
  bad() { echo "FAIL: $*"; fail=1; }
sa_can() {
  local ns="$1" sa="$2" a; shift 2
  local args=()
  for a in "$@"; do
    case "$a" in
      pods/*|nodes/*|certificatesigningrequests*/*) args+=("${a%%/*}" "--subresource=${a#*/}") ;;
      *) args+=("$a") ;;
    esac
  done
  kubectl auth can-i "${args[@]}" --as="system:serviceaccount:${ns}:${sa}" 2>/dev/null || true
}
  # expect_allowed <description> <ns> <sa> <can-i args>
  expect_allowed() { local d="$1" ns="$2" sa="$3"; shift 3; [ "$(sa_can "$ns" "$sa" "$@")" = "yes" ] || bad "$sa cannot $d"; }
  # expect_denied <description> <ns> <sa> <can-i args>
  expect_denied() { local d="$1" ns="$2" sa="$3"; shift 3; [ "$(sa_can "$ns" "$sa" "$@")" = "no" ] || bad "$sa is allowed to $d"; }

expect_allowed "get nodes" starfleet monitor get nodes
expect_allowed "list nodes" starfleet monitor list nodes
expect_allowed "get nodes/metrics" starfleet monitor get nodes/metrics
expect_allowed "get nodes/stats" starfleet monitor get nodes/stats

if [ "$fail" -eq 0 ]; then
  echo "PASS: monitor can read nodes, metrics and stats"
fi
exit "$fail"
